#!/usr/bin/env node
// Copies contract ABIs from Foundry's build output (contracts/out) into packages/sdk/src/abi as
// typed `as const` modules, so viem infers event and function types.
//
//   node tools/gen_abis.mjs           write the modules (run after `forge build`)
//   node tools/gen_abis.mjs --check   exit 1 if a module differs from the build output (CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'contracts', 'out');
const dest = join(root, 'packages', 'sdk', 'src', 'abi');

// [artifact, export name, keep]: keep = 'all' or 'events' (only events are needed from
// third-party contracts the indexer listens to).
const CONTRACTS = [
  ['MiningCore', 'miningCoreAbi', 'all'],
  ['MohnToken', 'mohnTokenAbi', 'all'],
  ['RevenueRouter', 'revenueRouterAbi', 'all'],
  ['BuybackBurner', 'buybackBurnerAbi', 'all'],
  ['LiquidityManager', 'liquidityManagerAbi', 'all'],
  ['TimelockController', 'timelockControllerAbi', 'all'],
  ['IPoolManager', 'poolManagerEventsAbi', 'events'],
];

const check = process.argv.includes('--check');
let stale = 0;
for (const [name, exportName, keep] of CONTRACTS) {
  const artifact = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact)) {
    console.error(`missing ${artifact}: run forge build in contracts/ first`);
    process.exit(1);
  }
  let abi = JSON.parse(readFileSync(artifact, 'utf8')).abi;
  if (keep === 'events') abi = abi.filter((item) => item.type === 'event');
  const body =
    `// Generated by tools/gen_abis.mjs from contracts/out/${name}.sol/${name}.json. Do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  const file = join(dest, `${name}.ts`);
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (current === body) continue;
  if (check) {
    console.error(`stale: ${file}`);
    stale += 1;
  } else {
    writeFileSync(file, body);
    console.log(`wrote ${file}`);
  }
}
if (stale > 0) {
  console.error('ABIs are out of date: run node tools/gen_abis.mjs and commit the result');
  process.exit(1);
}
