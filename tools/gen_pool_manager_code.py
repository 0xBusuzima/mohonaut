"""Writes contracts/test/recon/market/PoolManagerCode.sol from the PoolManager runtime fixture.

Medusa and Echidna cannot read files, so the property harness for the market layer carries the
Uniswap v4 PoolManager runtime bytecode of Robinhood Chain as a constant (its code hash is checked
like in the Foundry tests). Medusa does not run code placed with `etch`, so the harness deploys the
runtime with CREATE instead; the only place the code embeds its own address is the immutable of
NoDelegateCall, whose offset is emitted here so the harness can patch in the new address.

    python tools/gen_pool_manager_code.py           # write
    python tools/gen_pool_manager_code.py --check   # fail if the file is stale (CI)
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "contracts" / "test" / "fixtures" / "PoolManager.runtime.hex"
OUT = ROOT / "contracts" / "test" / "recon" / "market" / "PoolManagerCode.sol"
CANONICAL = "8366a39cc670b4001a1121b8f6a443a643e40951"


def render() -> str:
    code = FIXTURE.read_text(encoding="ascii").strip()
    if code.startswith("0x"):
        code = code[2:]
    int(code, 16)  # hex only
    hits = [i for i in range(0, len(code), 2) if code.lower().startswith(CANONICAL, i)]
    if len(hits) != 1:
        sys.exit(f"expected the PoolManager address once in its code, found {len(hits)}")
    return (
        "// SPDX-License-Identifier: MIT\n"
        "pragma solidity 0.8.30;\n"
        "\n"
        "// Generated by tools/gen_pool_manager_code.py from test/fixtures/PoolManager.runtime.hex.\n"
        "// Do not edit.\n"
        "\n"
        "/// @notice The Uniswap v4 PoolManager runtime bytecode of Robinhood Chain, for the property\n"
        "///         fuzzers (they cannot read the fixture file).\n"
        "library PoolManagerCode {\n"
        "    /// @notice Byte offset of the address NoDelegateCall keeps as an immutable.\n"
        f"    uint256 internal constant SELF_OFFSET = {hits[0] // 2};\n"
        "    bytes internal constant RUNTIME =\n"
        f'        hex"{code}";\n'
        "}\n"
    )


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="ascii") != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run python tools/gen_pool_manager_code.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="ascii", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
